"""
period_forecast_display.py

Pure formatting helpers for weekly / monthly Control Panel panels.
No Qt, no ML, no database imports — safe for unit tests.

Displays periods using **Jalali (Shamsi)** month names.
Database still stores Gregorian dates; only the label is converted.
"""

from __future__ import annotations

from typing import Any


def _jalali_month_label(month_start) -> str:
    """Convert a Gregorian month_start to a Shamsi month label."""
    try:
        from datetime import date as _date
        import sys
        from pathlib import Path

        # Ensure src/ is on path so jalali_calendar can be imported
        src = Path(__file__).resolve().parents[2]
        if str(src) not in sys.path:
            sys.path.insert(0, str(src))

        from jalali_calendar import jalali_month_label

        d = _date.fromisoformat(str(month_start)[:10])
        return jalali_month_label(d, lang="fa")
    except Exception:
        return str(month_start)


def format_weekly_summary(device_id: int, data: dict[str, Any]) -> str:
    """Human-readable weekly forecast text for the Control Panel."""
    if not data.get("found"):
        err = data.get("error")
        if err:
            return (
                f"Device {device_id}: weekly prediction unavailable "
                f"({err})."
            )
        return (
            f"Device {device_id}: no weekly prediction stored yet.\n"
            "Weekly forecasts are generated by the scheduler every "
            "Saturday (Shamsi week: Saturday → Friday total kWh)."
        )

    pred = data.get("predicted_consumption_kwh")
    week_start = data.get("week_start", "?")
    week_end = data.get("week_end", "?")
    model = data.get("model_version", "?")
    generated = data.get("generated_at", "?")

    if pred is None:
        body = (
            "Predicted consumption for next week: unavailable "
            "(insufficient history)."
        )
    else:
        body = f"Predicted consumption for next week: {float(pred):.1f} kWh"

    return (
        f"Device {device_id}\n"
        f"هفته شمسی: {week_start} → {week_end}\n"
        f"{body}\n"
        f"Model: {model}  ·  Generated: {generated}"
    )


def format_monthly_summary(device_id: int, data: dict[str, Any]) -> str:
    """Human-readable monthly forecast text for the Control Panel (Shamsi months)."""
    if not data.get("found"):
        err = data.get("error")
        if err:
            return (
                f"Device {device_id}: monthly prediction unavailable "
                f"({err})."
            )
        return (
            f"Device {device_id}: no monthly prediction stored yet.\n"
            "Monthly forecasts are generated by the scheduler on the "
            "1st of each Jalali (Shamsi) month (full Shamsi month total kWh)."
        )

    pred = data.get("predicted_consumption_kwh")
    month_start = data.get("month_start", "?")
    month_end = data.get("month_end", "?")
    model = data.get("model_version", "?")
    generated = data.get("generated_at", "?")

    # Shamsi month name instead of "September 2026"
    month_label = _jalali_month_label(month_start)

    if pred is None:
        body = (
            f"Predicted consumption for {month_label}: unavailable "
            f"(insufficient history)."
        )
    else:
        body = (
            f"Predicted consumption for {month_label}: {float(pred):.1f} kWh"
        )

    return (
        f"Device {device_id}\n"
        f"{month_label}\n"
        f"{month_start} → {month_end}\n"
        f"{body}\n"
        f"Model: {model}  ·  Generated: {generated}"
    )
